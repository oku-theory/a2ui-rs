"""Tests for fuzz_lock: fuzz/Cargo.lock assembled from Cargo.lock and fuzz/fuzz-only.lock."""

import contextlib
import io
import pathlib
import tempfile
import unittest

from fuzz_lock import LockError, assemble, blocks, main, pins, semver_line, unpinned

REGISTRY = "registry+https://github.com/rust-lang/crates.io-index"
HEADER = "# This file is automatically @generated by Cargo.\nversion = 4\n"


def package(name, version, dependencies=(), source=REGISTRY):
    """One `[[package]]` block, as Cargo writes it."""
    text = f'[[package]]\nname = "{name}"\nversion = "{version}"\n'
    if source:
        text += f'source = "{source}"\n'
    if dependencies:
        text += "dependencies = [\n" + "".join(f' "{d}",\n' for d in dependencies) + "]\n"
    return text


def lock(*blocks):
    """A lock file holding `blocks`."""
    return HEADER + "".join("\n" + block for block in blocks)


class AssembleTest(unittest.TestCase):
    def test_assemble_shared_line_takes_root_version(self):
        root = lock(package("itoa", "1.0.15"))
        pinned = lock(package("itoa", "1.0.11"))
        self.assertIn('version = "1.0.15"', assemble(root, pinned))
        self.assertNotIn('version = "1.0.11"', assemble(root, pinned))

    def test_assemble_line_root_lacks_adds_pin(self):
        root = lock(package("getrandom", "0.3.4"))
        pinned = lock(package("getrandom", "0.4.3"))
        assembled = assemble(root, pinned)
        self.assertIn('version = "0.3.4"', assembled)
        self.assertIn('version = "0.4.3"', assembled)

    def test_assemble_major_lines_differ(self):
        root = lock(package("shlex", "1.3.0"))
        pinned = lock(package("shlex", "2.0.1"))
        self.assertIn('version = "2.0.1"', assemble(root, pinned))

    def test_assemble_whole_output_root_then_pins(self):
        root = lock(package("itoa", "1.0.15"))
        pinned = lock(package("itoa", "1.0.11"), package("cc", "1.11.1"))
        self.assertEqual(
            assemble(root, pinned), lock(package("itoa", "1.0.15"), package("cc", "1.11.1"))
        )

    def test_assemble_second_release_qualifies_bare_dependencies(self):
        root = lock(package("ahash", "0.8.12", ["getrandom"]), package("getrandom", "0.3.4"))
        pinned = lock(package("jobserver", "0.1.35", ["getrandom"]), package("getrandom", "0.4.3"))
        assembled = assemble(root, pinned)
        self.assertIn(' "getrandom 0.3.4",', assembled)
        self.assertIn(' "getrandom 0.4.3",', assembled)
        self.assertNotIn(' "getrandom",', assembled)

    def test_assemble_unique_name_stays_bare(self):
        root = lock(package("serde_json", "1.0.154", ["itoa"]), package("itoa", "1.0.15"))
        self.assertIn(' "itoa",', assemble(root, lock()))


class SemverLineTest(unittest.TestCase):
    def test_semver_line_same_major_shares_line(self):
        self.assertEqual(semver_line("a", "1.0.3"), semver_line("a", "1.4.0"))

    def test_semver_line_same_zero_minor_shares_line(self):
        self.assertEqual(semver_line("a", "0.3.4"), semver_line("a", "0.3.9"))

    def test_semver_line_zero_minors_differ(self):
        self.assertNotEqual(semver_line("a", "0.3.4"), semver_line("a", "0.4.0"))

    def test_semver_line_zero_zero_patches_differ(self):
        self.assertNotEqual(semver_line("a", "0.0.3"), semver_line("a", "0.0.4"))

    def test_semver_line_pre_release_is_its_own(self):
        self.assertNotEqual(semver_line("a", "1.0.0-alpha.1"), semver_line("a", "1.2.0"))

    def test_semver_line_build_metadata_ignored(self):
        self.assertEqual(semver_line("a", "1.0.0+wasi"), semver_line("a", "1.2.0"))


class BlocksTest(unittest.TestCase):
    def test_blocks_other_table_fails(self):
        with self.assertRaises(LockError):
            blocks(lock(package("itoa", "1.0.15")) + "\n[metadata]\nx = 1\n")

    def test_blocks_no_package_is_header_only(self):
        self.assertEqual(blocks(HEADER), (HEADER, []))

    def test_assemble_keeps_root_header(self):
        root = lock(package("itoa", "1.0.15"))
        self.assertTrue(assemble(root, lock()).startswith(HEADER))


class UnpinnedTest(unittest.TestCase):
    def test_unpinned_release_in_neither_is_listed(self):
        final = lock(package("itoa", "1.0.15"), package("cc", "1.12.0"))
        root = lock(package("itoa", "1.0.15"))
        pinned = lock(package("cc", "1.11.1"))
        self.assertEqual(unpinned(final, root, pinned), [("cc", "1.12.0", REGISTRY)])

    def test_unpinned_shared_crate_off_root_release_is_listed(self):
        final = lock(package("itoa", "1.0.19"))
        root = lock(package("itoa", "1.0.15"))
        pinned = lock(package("itoa", "1.0.19"))
        self.assertEqual(unpinned(final, root, pinned), [("itoa", "1.0.19", REGISTRY)])

    def test_unpinned_other_source_is_listed(self):
        fork = "git+https://example.com/cc?rev=1#0123"
        final = lock(package("cc", "1.11.1", source=fork))
        self.assertEqual(
            unpinned(final, lock(), lock(package("cc", "1.11.1"))), [("cc", "1.11.1", fork)]
        )

    def test_unpinned_assembled_lock_itself_is_empty(self):
        root = lock(package("getrandom", "0.3.4"), package("itoa", "1.0.15"))
        pinned = lock(package("getrandom", "0.4.3"), package("itoa", "1.0.11"))
        self.assertEqual(unpinned(assemble(root, pinned), root, pinned), [])

    def test_unpinned_root_or_pin_or_path_is_empty(self):
        final = lock(
            package("a2ui-fuzz", "0.0.0", source=None),
            package("itoa", "1.0.15"),
            package("cc", "1.11.1"),
        )
        root = lock(package("itoa", "1.0.15"))
        pinned = lock(package("cc", "1.11.1"))
        self.assertEqual(unpinned(final, root, pinned), [])


class PinsTest(unittest.TestCase):
    final = lock(
        package("a2ui-fuzz", "0.0.0", ["a2ui-runtime", "libfuzzer-sys", "serde_json"], None),
        package("a2ui-runtime", "0.2.0", ["memchr", "serde_json"], None),
        package("libfuzzer-sys", "0.4.13", ["arbitrary", "cc"]),
        package("cc", "1.11.1", ["libc"]),
        package("arbitrary", "1.5.0"),
        package("libc", "0.2.170"),
        package("serde_json", "1.0.154", ["itoa"]),
        package("itoa", "1.0.15"),
        package("memchr", "2.7.4"),
    )

    def names(self, text):
        return [line.split('"')[1] for line in text.splitlines() if line.startswith("name = ")]

    def test_pins_fuzz_dependencies_transitively(self):
        self.assertEqual(
            self.names(pins(self.final)),
            ["arbitrary", "cc", "itoa", "libc", "libfuzzer-sys", "serde_json"],
        )

    def test_pins_leave_out_what_only_path_crates_reach(self):
        self.assertNotIn("memchr", self.names(pins(self.final)))

    def test_pins_diamond_and_cycle_reach_each_once(self):
        final = lock(
            package("a2ui-fuzz", "0.0.0", ["a", "b"], None),
            package("a", "1.0.0", ["c"]),
            package("b", "1.0.0", ["c"]),
            package("c", "1.0.0", ["a"]),
        )
        self.assertEqual(self.names(pins(final)), ["a", "b", "c"])

    def test_pins_without_fuzz_crate_fails(self):
        with self.assertRaises(LockError):
            pins(lock(package("itoa", "1.0.15")))

    def test_pins_dangling_dependency_fails(self):
        with self.assertRaises(LockError):
            pins(lock(package("a2ui-fuzz", "0.0.0", ["gone"], None)))

    def test_pins_versioned_dependency_picks_that_release(self):
        final = lock(
            package("a2ui-fuzz", "0.0.0", ["getrandom 0.4.3"], None),
            package("getrandom", "0.3.4"),
            package("getrandom", "0.4.3"),
        )
        self.assertIn('version = "0.4.3"', pins(final))
        self.assertNotIn('version = "0.3.4"', pins(final))


class MainTest(unittest.TestCase):
    def run_main(self, files, *args):
        with tempfile.TemporaryDirectory() as directory:
            base = pathlib.Path(directory)
            (base / "fuzz").mkdir()
            for name, text in files.items():
                (base / name).write_text(text)
            err = io.StringIO()
            with contextlib.redirect_stderr(err), contextlib.redirect_stdout(io.StringIO()):
                code = main([*args, "--root", str(base)])
            written = {
                path.relative_to(base).as_posix(): path.read_text()
                for path in base.rglob("*.lock")
            }
            return code, err.getvalue(), written

    def test_main_verify_unpinned_fails_naming_fuzz_lock(self):
        files = {
            "Cargo.lock": lock(package("itoa", "1.0.15")),
            "fuzz/fuzz-only.lock": lock(),
            "fuzz/Cargo.lock": lock(package("itoa", "1.0.15"), package("cc", "1.12.0")),
        }
        code, err, _ = self.run_main(files, "verify")
        self.assertEqual(code, 1)
        self.assertIn("cc 1.12.0", err)
        self.assertIn("just fuzz-lock", err)

    def test_main_verify_pinned_passes(self):
        files = {
            "Cargo.lock": lock(package("itoa", "1.0.15")),
            "fuzz/fuzz-only.lock": lock(package("cc", "1.11.1")),
            "fuzz/Cargo.lock": lock(package("itoa", "1.0.15"), package("cc", "1.11.1")),
        }
        self.assertEqual(self.run_main(files, "verify")[0], 0)

    def test_main_assemble_writes_fuzz_cargo_lock(self):
        files = {
            "Cargo.lock": lock(package("itoa", "1.0.15")),
            "fuzz/fuzz-only.lock": lock(package("cc", "1.11.1")),
        }
        code, _, written = self.run_main(files, "assemble")
        self.assertEqual(code, 0)
        self.assertIn('name = "cc"', written["fuzz/Cargo.lock"])

    def test_main_pin_rewrites_pins_from_fuzz_cargo_lock(self):
        files = {
            "Cargo.lock": lock(),
            "fuzz/fuzz-only.lock": lock(package("cc", "1.11.1")),
            "fuzz/Cargo.lock": lock(
                package("a2ui-fuzz", "0.0.0", ["cc"], None), package("cc", "1.12.0")
            ),
        }
        code, _, written = self.run_main(files, "pin")
        self.assertEqual(code, 0)
        self.assertIn('version = "1.12.0"', written["fuzz/fuzz-only.lock"])

    def test_main_verify_shared_crate_names_root_release(self):
        files = {
            "Cargo.lock": lock(package("itoa", "1.0.15")),
            "fuzz/fuzz-only.lock": lock(),
            "fuzz/Cargo.lock": lock(package("itoa", "1.0.19")),
        }
        code, err, _ = self.run_main(files, "verify")
        self.assertEqual(code, 1)
        self.assertIn("itoa 1.0.19 (Cargo.lock holds 1.0.15)", err)

    def test_main_missing_lock_fails_with_message(self):
        code, err, _ = self.run_main({"Cargo.lock": lock()}, "assemble")
        self.assertEqual(code, 1)
        self.assertIn("fuzz-only.lock", err)

    def test_main_pin_lists_only_releases_cargo_lock_lacks(self):
        files = {
            "Cargo.lock": lock(package("itoa", "1.0.15")),
            "fuzz/fuzz-only.lock": lock(),
            "fuzz/Cargo.lock": lock(
                package("a2ui-fuzz", "0.0.0", ["cc", "itoa"], None),
                package("cc", "1.12.0"),
                package("itoa", "1.0.15"),
            ),
        }
        with tempfile.TemporaryDirectory() as directory:
            base = pathlib.Path(directory)
            (base / "fuzz").mkdir()
            for name, text in files.items():
                (base / name).write_text(text)
            out = io.StringIO()
            with contextlib.redirect_stdout(out):
                main(["pin", "--root", str(base)])
        self.assertIn("cc 1.12.0", out.getvalue())
        self.assertNotIn("itoa", out.getvalue())

    def test_main_unknown_command_fails(self):
        with contextlib.redirect_stderr(io.StringIO()), self.assertRaises(SystemExit) as raised:
            main(["frobnicate"])
        self.assertEqual(raised.exception.code, 2)


if __name__ == "__main__":
    unittest.main()
